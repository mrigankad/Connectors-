"""Generate the Python and TypeScript SDKs from packages/contracts/openapi.json.

Python: a thin typed httpx client (one method per operationId) written to packages/sdk-python.
TypeScript: schema types via openapi-typescript (npx, pinned) plus a small fetch client.
Both are generated artefacts; re-run after changing the API and commit the result (CI checks freshness).
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "packages" / "contracts" / "openapi.json"
PY_OUT = ROOT / "packages" / "sdk-python" / "wayam_connectors_sdk" / "client.py"
TS_DIR = ROOT / "packages" / "sdk-typescript"
OPENAPI_TS_VERSION = "7.6.1"


def _snake(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def gen_python(spec: dict) -> str:
    lines = [
        '"""Generated by scripts/generate_sdks.py from packages/contracts/openapi.json. Do not edit."""',
        "from __future__ import annotations",
        "",
        "from typing import Any",
        "",
        "import httpx",
        "",
        "",
        "class WayamConnectorsError(Exception):",
        "    def __init__(self, status: int, body: Any) -> None:",
        "        super().__init__(f'{status}: {body}')",
        "        self.status = status",
        "        self.body = body",
        "",
        "",
        "class WayamConnectorsClient:",
        '    """Sync client for the Wayam Connector Platform control API. Tenant identity comes from the API key."""',
        "",
        "    def __init__(self, base_url: str, api_key: str, *, timeout: float = 30.0) -> None:",
        "        self._c = httpx.Client(base_url=base_url, headers={'Authorization': f'Bearer {api_key}'}, timeout=timeout)",
        "",
        "    def close(self) -> None:",
        "        self._c.close()",
        "",
        "    def _call(self, method: str, path: str, *, params: dict[str, Any] | None = None, json: Any = None) -> Any:",
        "        r = self._c.request(method, path, params=params, json=json)",
        "        if r.status_code >= 400:",
        "            try:",
        "                body = r.json()",
        "            except ValueError:",
        "                body = r.text",
        "            raise WayamConnectorsError(r.status_code, body)",
        "        return r.json() if r.content else None",
    ]
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            if method not in ("get", "post", "put", "delete", "patch"):
                continue
            name = _snake(op.get("operationId") or f"{method}_{path}")
            name = re.sub(r"_(get|post|put|delete|patch)$", "", name)
            path_params = [p["name"] for p in op.get("parameters", []) if p["in"] == "path"]
            query_params = [p["name"] for p in op.get("parameters", []) if p["in"] == "query"]
            has_body = "requestBody" in op
            args = ["self"] + [f"{_snake(p)}: str" for p in path_params]
            if has_body:
                args.append("body: dict[str, Any]")
            args += [f"{_snake(q)}: Any = None" for q in query_params]
            fmt_path = re.sub(r"\{([^}]+)\}", lambda m: "{" + _snake(m.group(1)) + "}", path)
            lines += [
                "",
                f"    def {name}({', '.join(args)}) -> Any:",
                f'        """{op.get("summary") or name}: {method.upper()} {path}"""',
            ]
            q = "{" + ", ".join(f"'{qp}': {_snake(qp)}" for qp in query_params) + "}" if query_params else "None"
            lines.append(f"        return self._call('{method.upper()}', f'{fmt_path}', params={q}{', json=body' if has_body else ''})")
    return "\n".join(lines) + "\n"


def gen_typescript(spec: dict) -> None:
    TS_DIR.mkdir(parents=True, exist_ok=True)
    (TS_DIR / "package.json").write_text(
        json.dumps(
            {
                "name": "@wayam/connectors-sdk",
                "version": spec["info"]["version"],
                "private": True,
                "type": "module",
                "main": "client.ts",
                "scripts": {"generate": f"npx -y openapi-typescript@{OPENAPI_TS_VERSION} ../contracts/openapi.json -o schema.d.ts"},
            },
            indent=2,
        )
        + "\n"
    )
    try:
        subprocess.run(  # noqa: S603 - fixed, pinned generator invocation
            ["npx", "-y", f"openapi-typescript@{OPENAPI_TS_VERSION}", str(SPEC), "-o", str(TS_DIR / "schema.d.ts")],  # noqa: S607
            check=True,
            cwd=TS_DIR,
            capture_output=True,
            text=True,
            timeout=600,
        )
    except (subprocess.CalledProcessError, FileNotFoundError, subprocess.TimeoutExpired) as exc:
        sys.stderr.write(f"openapi-typescript not run ({type(exc).__name__}); schema.d.ts left as is\n")
    client = """// Generated by scripts/generate_sdks.py. Thin fetch client over the OpenAPI contract; types in schema.d.ts.
import type { paths } from "./schema";

export class WayamConnectorsError extends Error {
  constructor(public status: number, public body: unknown) {
    super(`${status}: ${JSON.stringify(body)}`);
  }
}

export class WayamConnectorsClient {
  constructor(private baseUrl: string, private apiKey: string, private fetchImpl: typeof fetch = fetch) {}

  async call<P extends keyof paths, M extends keyof paths[P] & string>(
    path: P, method: M, opts: { params?: Record<string, string>; query?: Record<string, string>; body?: unknown } = {}
  ): Promise<unknown> {
    let url = String(path);
    for (const [k, v] of Object.entries(opts.params ?? {})) url = url.replace(`{${k}}`, encodeURIComponent(v));
    const qs = opts.query ? "?" + new URLSearchParams(opts.query).toString() : "";
    const res = await this.fetchImpl(this.baseUrl + url + qs, {
      method: method.toUpperCase(),
      headers: { Authorization: `Bearer ${this.apiKey}`, "Content-Type": "application/json" },
      body: opts.body === undefined ? undefined : JSON.stringify(opts.body),
    });
    const body = res.status === 204 ? null : await res.json();
    if (!res.ok) throw new WayamConnectorsError(res.status, body);
    return body;
  }
}
"""
    (TS_DIR / "client.ts").write_text(client)


if __name__ == "__main__":
    spec = json.loads(SPEC.read_text())
    PY_OUT.parent.mkdir(parents=True, exist_ok=True)
    PY_OUT.write_text(gen_python(spec))
    (PY_OUT.parent / "__init__.py").write_text(
        'from .client import WayamConnectorsClient, WayamConnectorsError\n\n__all__ = ["WayamConnectorsClient", "WayamConnectorsError"]\n'
    )
    version = spec["info"]["version"]
    (PY_OUT.parent.parent / "pyproject.toml").write_text(
        "[project]\n"
        'name = "wayam-connectors-sdk"\n'
        f'version = "{version}"\n'
        'description = "Generated client for the Wayam Connector Platform API"\n'
        'requires-python = ">=3.12"\n'
        'dependencies = ["httpx>=0.28,<1"]\n\n'
        "[build-system]\n"
        'requires = ["hatchling"]\n'
        'build-backend = "hatchling.build"\n\n'
        "[tool.hatch.build.targets.wheel]\n"
        'packages = ["wayam_connectors_sdk"]\n'
    )
    if "--python-only" not in sys.argv:
        gen_typescript(spec)
    sys.stdout.write(f"python sdk -> {PY_OUT}\ntypescript sdk -> {TS_DIR}\n")
